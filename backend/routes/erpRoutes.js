const express = require('express')
const controller = require('../controllers/erpController')
const { authenticate, authorize } = require('../middleware/authenticate')

const router = express.Router()

router.get('/health', (req, res) => {
  const healthy = req.app.get('mongooseConnection').readyState === 1
  res.status(healthy ? 200 : 503).json({ status: healthy ? 'ok' : 'degraded', database: healthy ? 'connected' : 'disconnected' })
})
router.use(authenticate)
router.get('/portal', authorize('portal.read'), controller.getPortal)
router.get('/students', authorize('students.read'), controller.getStudents)
router.get('/students/analytics', authorize('analytics.read'), controller.getStudentAnalytics)
router.get('/students/:id', authorize('students.read'), controller.getStudent)
router.post('/students', authorize('students.manage'), controller.createStudent)
router.put('/students/:id', authorize('students.manage'), controller.updateStudent)
router.delete('/students/:id', authorize('students.manage'), controller.deleteStudent)
router.post('/students/bulk-delete', authorize('students.manage'), controller.bulkDeleteStudents)
router.post('/students/bulk-import', authorize('students.manage'), controller.bulkImportStudents)

router.get('/courses', authorize('courses.read'), controller.getCourses)
router.post('/courses', authorize('courses.manage'), controller.createCourse)
router.put('/courses/:id', authorize('courses.manage'), controller.updateCourse)
router.delete('/courses/:id', authorize('courses.manage'), controller.deleteCourse)
router.get('/instructors', authorize('instructors.read'), controller.getInstructors)
router.post('/instructors', authorize('instructors.manage'), controller.createInstructor)
router.put('/instructors/:id', authorize('instructors.manage'), controller.updateInstructor)
router.delete('/instructors/:id', authorize('instructors.manage'), controller.deleteInstructor)
router.get('/lectures', authorize('courses.read'), controller.getLectures)
router.post('/lectures', authorize('courses.manage'), controller.createLecture)
router.put('/lectures/:id', authorize('courses.manage'), controller.updateLecture)
router.delete('/lectures/:id', authorize('courses.manage'), controller.deleteLecture)
