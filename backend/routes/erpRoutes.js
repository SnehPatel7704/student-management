router.put('/lectures/:id/attendance', authorize('attendance.manage'), controller.saveLectureAttendance)

router.get('/internships', authorize('internships.read'), controller.getInternships)
router.post('/internships', authorize('internships.manage'), controller.createInternship)
router.put('/internships/:id', authorize('internships.manage'), controller.updateInternship)
router.delete('/internships/:id', authorize('internships.manage'), controller.deleteInternship)
router.post('/internships/:id/apply', authorize('internships.apply'), controller.applyInternship)
router.get('/clubs', authorize('clubs.read'), controller.getClubs)
router.post('/clubs', authorize('clubs.manage'), controller.createClub)
router.put('/clubs/:id', authorize('clubs.manage'), controller.updateClub)
router.delete('/clubs/:id', authorize('clubs.manage'), controller.deleteClub)
router.post('/clubs/:id/join', authorize('clubs.join'), controller.joinClub)

router.post('/attendance', authorize('attendance.manage'), controller.logAttendance)
router.put('/attendance/:id', authorize('attendance.manage'), controller.updateAttendance)
router.delete('/attendance/:id', authorize('attendance.manage'), controller.deleteAttendance)
router.get('/attendance/student/:id', authorize('attendance.read'), controller.getStudentAttendance)
router.post('/grades', authorize('grades.manage'), controller.recordGrade)
router.put('/grades/:id', authorize('grades.manage'), controller.updateGrade)
router.delete('/grades/:id', authorize('grades.manage'), controller.deleteGrade)
router.get('/grades/student/:studentId', authorize('grades.read'), controller.getStudentGrades)

